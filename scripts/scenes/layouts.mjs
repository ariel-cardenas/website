export function hotspotStyles() {
  const selectors = { news: "mailbox" };
  const rules = (orientation) => Object.entries(layouts).map(([weather, variants]) =>
    Object.entries(variants[orientation].landmarks).map(([name, point]) =>
      `.experience[data-weather="${weather}"] .hotspot--${selectors[name] || name} { --x: ${point.x}%; --y: ${point.y}%; --hit-w: ${point.hitWidth}%; --hit-h: ${point.hitHeight}%; }`,
    ).join("\n"),
  ).join("\n\n");
  return `/* Generated by npm run build:scenes. Edit scripts/scenes/layouts.mjs. */\n${rules("horizontal")}\n\n@media (max-width: 700px) {\n${rules("vertical")}\n}\n`;
}
