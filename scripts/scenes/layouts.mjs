function layout(width, height, points, hits) {
  return {
    width, height,
    landmarks: Object.fromEntries(Object.entries(points).map(([name, [x, y]]) =>
      [name, { x, y, hitWidth: hits[name][0], hitHeight: hits[name][1] }],
    )),
  };
}

